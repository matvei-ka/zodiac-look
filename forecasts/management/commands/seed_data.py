class Command(BaseCommand):
    help = 'Заполняет базу цветами удачи и готовыми образами'

    def handle(self, *args, **options):
        for mood, name, hex_code, meaning in COLORS:
            Color.objects.get_or_create(
                name=name,
                defaults={'hex_code': hex_code, 'meaning': meaning, 'mood': mood},
            )
        colors = {color.name: color for color in Color.objects.all()}
        for mood, title, items, color_name in OUTFITS:
            Outfit.objects.get_or_create(
                title=title,
                defaults={'items': items, 'mood': mood, 'color': colors[color_name]},
            )
        self.stdout.write(
            self.style.SUCCESS(
                f'Готово: цветов {Color.objects.count()}, образов {Outfit.objects.count()}'
            )
        )